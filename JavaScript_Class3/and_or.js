// && -> AND Gate
// || -> OR Gate

let a = true;
let b = false;

console.log(a && b); // false
console.log(a || b); // true
console.log(!a); // false
console.log(!b); // true

console.log(""==false); // true
console.log(""===false); // false

console.log(""==0); // true
console.log(""===0); // false
console.log("0"==0); // true
console.log("0"===0); // false
console.log(""=="0"); // false
console.log(""==="0"); // false